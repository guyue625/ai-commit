export function getTranslations(locale?: string): TranslationDictionary {
  const normalized = locale?.toLocaleLowerCase();
  return normalized === 'zh-cn' || normalized?.startsWith('zh-hans')
    ? ZH_CN_TRANSLATIONS
    : EN_TRANSLATIONS;
}
